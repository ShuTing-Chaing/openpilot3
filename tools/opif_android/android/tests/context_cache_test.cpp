#include "../native/qnn_context_cache.h"
#include <cassert>
#include <fstream>
#include <iostream>

using opif::context_cache::Store;

template<class Function> void rejects(Function function) {
  bool rejected = false;
  try { function(); } catch (const std::exception&) { rejected = true; }
  assert(rejected);
}

void write_file(const std::string& path, const std::string& content) {
  std::ofstream file(path, std::ios::binary | std::ios::trunc);
  file << content;
  file.close();
  assert(file);
}

int main() {
  using opif::context_cache::sha256;
  using opif::context_cache::Sha256;
  assert(sha256("") == "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855");
  assert(sha256("abc") == "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad");
  assert(sha256("abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq") ==
         "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1");
  Sha256 streaming;
  const std::string block(1000, 'a');
  for (unsigned i = 0; i < 1000; ++i) streaming.update(block.data(), block.size());
  assert(streaming.finish() == "cdc76e5c9914fb9281a1c7e284d73e67f1809a48a497200e046d39ccc7112cd0");

  char root_pattern[] = "/tmp/opif-context-cache-XXXXXX";
  const char* created = mkdtemp(root_pattern);
  assert(created);
  const std::string root = created;
  const std::string cache_root = root + "/contexts";
  const std::string identity = "model-sha+runtime-sha+driver-fingerprint+options";
  const std::string payload(1024 * 257 + 13, 'x');
  std::string pending, ready;
  {
    Store store(cache_root, identity);
    assert(store.load().empty());
    rejects([&] { Store concurrent(cache_root, identity); });
    pending = store.begin();
    write_file(pending, payload);
    // Generated bytes without a success manifest are never considered committed.
    assert(store.load().empty());
  }
  assert(!std::filesystem::exists(pending));
  {
    Store store(cache_root, identity);
    assert(store.load().empty());
    pending = store.begin();
    write_file(pending, payload);
    store.commit();
    ready = store.load();
    assert(!ready.empty() && std::filesystem::exists(ready));
    assert(!std::filesystem::exists(pending));
  }
  {
    Store reopened(cache_root, identity);
    assert(reopened.load() == ready);
    // A same-size corruption must be rejected, even if filenames and mtime agree.
    std::string corrupted = payload;
    corrupted[100] ^= 1;
    write_file(ready, corrupted);
    rejects([&] { reopened.load(); });
    write_file(ready, payload);
    assert(reopened.load() == ready);
    write_file(std::filesystem::path(ready).parent_path().string() + "/manifest", "partial");
    rejects([&] { reopened.load(); });
    reopened.invalidate();
    assert(reopened.load().empty());
  }
  {
    // Different model/runtime/driver options cannot hit the old key.
    Store previous(cache_root, identity);
    write_file(previous.begin(), payload);
    previous.commit();
  }
  {
    Store changed(cache_root, identity + "-changed");
    assert(changed.load().empty());
    write_file(changed.begin(), "new-context");
    changed.commit();
    assert(!changed.load().empty());
    assert(!std::filesystem::exists(ready));
  }
  {
    Store empty(cache_root, "empty");
    write_file(empty.begin(), "");
    rejects([&] { empty.commit(); });
    assert(empty.load().empty());
  }
  {
    Store symlink(cache_root, "symlink");
    const auto staged = symlink.begin();
    const auto external = root + "/external";
    write_file(external, payload);
    std::filesystem::create_symlink(external, staged);
    rejects([&] { symlink.commit(); });
    assert(symlink.load().empty());
  }
  {
    // A killed writer's staging directory is discarded on the next initializer.
    const auto stale = cache_root + "/.pending-stale";
    std::filesystem::create_directory(stale);
    write_file(stale + "/context.onnx", payload);
    Store recovered(cache_root, identity);
    assert(!std::filesystem::exists(stale));
    assert(recovered.load().empty());
  }
  chmod(cache_root.c_str(), 0755);
  rejects([&] { Store public_directory(cache_root, identity); });
  std::filesystem::remove_all(root);
  std::cout << "Context cache integrity, atomic publication and invalidation checks passed\n";
}
